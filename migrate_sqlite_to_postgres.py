import os
import sqlite3
import psycopg2

SQLITE_FILE = "pharma.db"

pg = psycopg2.connect(
    host=os.environ.get("PGHOST", "localhost"),
    port=os.environ.get("PGPORT", "5432"),
    dbname=os.environ["PGDATABASE"],
    user=os.environ["PGUSER"],
    password=os.environ["PGPASSWORD"],
)

sqlite = sqlite3.connect(
    f"file:{SQLITE_FILE}?mode=ro", uri=True
)

try:
    with pg:
        with pg.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS medicines (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    batch TEXT UNIQUE NOT NULL,
                    manufacturer TEXT NOT NULL,
                    expiry TEXT NOT NULL
                )
            """)

            cur.execute("""
                CREATE TABLE IF NOT EXISTS events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    batch_id BIGINT NOT NULL,
                    status TEXT NOT NULL,
                    location TEXT NOT NULL,
                    timestamp TEXT NOT NULL,
                    previous_hash TEXT NOT NULL,
                    event_hash TEXT NOT NULL,
                    tx_hash TEXT,
                    chain_hash TEXT,
                    block_number BIGINT
                )
            """)

            cur.execute(
                "SELECT COUNT(*) FROM medicines"
            )
            medicine_count = cur.fetchone()[0]

            cur.execute("SELECT COUNT(*) FROM events")
            event_count = cur.fetchone()[0]

            if medicine_count or event_count:
                raise RuntimeError(
                    "Target tables are not empty. "
                    "Migration stopped to avoid overwriting data."
                )

            medicines = sqlite.execute("""
                SELECT id, name, batch, manufacturer, expiry
                FROM medicines ORDER BY id
            """).fetchall()

            events = sqlite.execute("""
                SELECT id, batch_id, status, location, timestamp,
                       previous_hash, event_hash, tx_hash,
                       chain_hash, block_number
                FROM events ORDER BY id
            """).fetchall()

            cur.executemany("""
                INSERT INTO medicines
                    (id, name, batch, manufacturer, expiry)
                VALUES (%s, %s, %s, %s, %s)
            """, medicines)

            cur.executemany("""
                INSERT INTO events
                    (id, batch_id, status, location, timestamp,
                     previous_hash, event_hash, tx_hash,
                     chain_hash, block_number)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """, events)

            for table in ("medicines", "events"):
                cur.execute(f"""
                    SELECT setval(
                        pg_get_serial_sequence('{table}', 'id'),
                        COALESCE(MAX(id), 1),
                        MAX(id) IS NOT NULL
                    )
                    FROM {table}
                """)

    print("Migration successful!")
    print(f"Medicines copied: {len(medicines)}")
    print(f"Events copied: {len(events)}")

except Exception:
    pg.rollback()
    raise

finally:
    sqlite.close()
    pg.close()
